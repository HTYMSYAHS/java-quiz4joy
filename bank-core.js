// Fill-in questions for the earlier course topics. Every custom name used in an
// answer is written in that question's prompt or snippet.

function fill(id, topic, prompt, code, answer, explanation, altAnswers) {
  const question = { id, topic, type: "fill", prompt, code, answer, explanation };
  if (altAnswers?.length) question.altAnswers = altAnswers;
  return question;
}

